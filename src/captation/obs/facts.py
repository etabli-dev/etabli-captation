"""Facts dump (``captation obs facts``): what this OBS on this OS actually offers.

Writes a generated section per OS into ``docs/platform-facts.md`` between markers, so a rerun
replaces it. The curated PF-ID table above the generated sections is maintained by hand.
"""

from __future__ import annotations

import json
import platform
import re
import time
from datetime import date
from pathlib import Path
from typing import Any

from captation.obs import kinds
from captation.obs.client import ObsError, ObsWebSocket

SCRATCH_SCENE = "Captation Facts Scratch"


def available_encoders(config_dir: Path) -> dict[str, set[str]]:
    """Parse the newest OBS log for the 'Available Encoders' section."""
    logs = sorted((config_dir / "logs").glob("*.txt"), key=lambda p: p.stat().st_mtime)
    result: dict[str, set[str]] = {"audio": set(), "video": set()}
    if not logs:
        return result
    section: str | None = None
    in_block = False
    for line in logs[-1].read_text(encoding="utf-8", errors="replace").splitlines():
        if kinds.LOG_ENCODERS_HEADER in line:
            in_block = True
            continue
        if not in_block:
            continue
        if kinds.LOG_VIDEO_ENCODERS in line:
            section = "video"
        elif kinds.LOG_AUDIO_ENCODERS in line:
            section = "audio"
        else:
            m = re.search(r"-\s+(\S+)\s+\(", line)
            if m and section:
                result[section].add(m.group(1))
            elif "====" in line or not line.strip():
                break
    return result


def _use_collection(ws: ObsWebSocket, name: str, timeout_s: float = 15) -> None:
    """Scratch inputs only ever go into the Captation collection (principles §4.2)."""
    R = ws.request
    if R("GetSceneCollectionList").get("currentSceneCollectionName") == name:
        return
    R("SetCurrentSceneCollection", {"sceneCollectionName": name})
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        if R("GetSceneCollectionList").get("currentSceneCollectionName") == name:
            return
        time.sleep(0.25)
    raise ObsError(f"OBS did not switch to the scene collection {name}")


def collect(ws: ObsWebSocket, config_dir: Path, collection: str | None = None) -> dict[str, Any]:
    R = ws.request
    if R("GetRecordStatus").get("outputActive"):
        raise ObsError("OBS is recording: run `captation obs facts` while OBS is idle")
    if collection is not None:
        _use_collection(ws, collection)
    version = R("GetVersion")
    facts: dict[str, Any] = {
        "obs_version": version.get("obsVersion"),
        "ws_version": version.get("obsWebSocketVersion"),
        "platform": version.get("platformDescription"),
        "set_record_directory": "SetRecordDirectory" in version.get("availableRequests", []),
        "request_count": len(version.get("availableRequests", [])),
        "input_kinds": R("GetInputKindList", {"unversioned": False})["inputKinds"],
        "encoders": {k: sorted(v) for k, v in available_encoders(config_dir).items()},
        "defaults": {},
        "list_items": {},
    }
    for kind in facts["input_kinds"]:
        try:
            facts["defaults"][kind] = R("GetInputDefaultSettings", {"inputKind": kind})[
                "defaultInputSettings"
            ]
        except ObsError:
            facts["defaults"][kind] = None
    scenes = [s["sceneName"] for s in R("GetSceneList")["scenes"]]
    if SCRATCH_SCENE not in scenes:
        R("CreateScene", {"sceneName": SCRATCH_SCENE})
    try:
        from captation.platform import current_os

        value_props = kinds.fact_value_properties(current_os())
        for kind, props in kinds.fact_list_properties(current_os()).items():
            if kind not in facts["input_kinds"]:
                continue
            name = f"Captation Facts {kind}"
            R("CreateInput", {"sceneName": SCRATCH_SCENE, "inputName": name, "inputKind": kind})
            try:
                for prop in props:
                    items = R(
                        "GetInputPropertiesListPropertyItems",
                        {"inputName": name, "propertyName": prop},
                    )["propertyItems"]
                    # Device and app names are machine-specific: keep values, count names.
                    facts["list_items"][f"{kind}.{prop}"] = [
                        i["itemValue"] if prop in value_props else "…" for i in items
                    ]
            finally:
                R("RemoveInput", {"inputName": name})
    finally:
        R("RemoveScene", {"sceneName": SCRATCH_SCENE})
    return facts


def render_section(os_name: str, facts: dict[str, Any], extra: dict[str, str]) -> str:
    lines = [
        f"<!-- facts:{os_name}:begin (generated by `captation obs facts`, do not edit) -->",
        f"### Facts dump: {os_name} ({date.today().isoformat()})",
        "",
        f"- OS: {platform.platform(terse=True)}",
        f"- OBS {facts['obs_version']}, obs-websocket {facts['ws_version']} ({facts['platform']})",
        f"- Requests: {facts['request_count']}; "
        f"SetRecordDirectory: {facts['set_record_directory']}",
        f"- Video encoders: {', '.join(facts['encoders']['video']) or '-'}",
        f"- Audio encoders: {', '.join(facts['encoders']['audio']) or '-'}",
    ]
    lines += [f"- {k}: {v}" for k, v in extra.items()]
    lines += ["", "| Input kind | Default settings |", "|---|---|"]
    for kind in facts["input_kinds"]:
        defaults = json.dumps(facts["defaults"].get(kind), sort_keys=True)
        lines.append(f"| `{kind}` | `{defaults}` |")
    if facts["list_items"]:
        lines += ["", "| List property | Items |", "|---|---|"]
        for key, items in facts["list_items"].items():
            lines.append(f"| `{key}` | {len(items)} item(s): `{json.dumps(items)}` |")
    lines.append(f"<!-- facts:{os_name}:end -->")
    return "\n".join(lines) + "\n"


def write_section(doc: Path, os_name: str, section: str) -> None:
    text = doc.read_text(encoding="utf-8")
    pattern = re.compile(
        rf"<!-- facts:{os_name}:begin.*?<!-- facts:{os_name}:end -->\n?", re.DOTALL
    )
    if pattern.search(text):
        text = pattern.sub(lambda _: section, text)
    else:
        text = text.rstrip("\n") + "\n\n" + section
    doc.write_text(text, encoding="utf-8")
